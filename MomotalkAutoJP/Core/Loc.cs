    /// "ui."로 시작하는 문구는 화면(XAML)에서 {DynamicResource ui.xxx}로 쓰이고, 언어를 바꾸면 바로 바뀜.
    /// 나머지는 코드에서 Loc.T("key")로 사용.
    /// </summary>
    public static class Loc
